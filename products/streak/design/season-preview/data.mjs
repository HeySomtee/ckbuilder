export const budget = 40;
export const findPlayer = (id) => players.find((p) => p.id === id);
export function draftTotal(draft) {
  return draft.reduce((sum, id) => sum + (findPlayer(id)?.price || 0), 0);
}
export function selectionError(draft, index, id) {
  const player = findPlayer(id);
  if (!player || !slots[index] || player.role !== slots[index].role)
    return "Choose a player for this position.";
  if (draft.some((p, i) => p === id && i !== index))
    return "This player is already in your five.";
  const next = [...draft];
  next[index] = id;
  if (draftTotal(next) > budget)
    return "That takes you over 40 credits. Choose a lower-priced player.";
  return "";
}
